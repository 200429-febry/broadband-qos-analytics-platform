type AnyObject = Record<string, any>;

const API_BASE =
  process.env.NEXT_PUBLIC_API_URL ||
  process.env.API_URL ||
  process.env.QOS_API_URL ||
  "https://qos-api-242258296786.asia-southeast2.run.app";

function n(value: any, fallback = 0): number {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}

function pick(obj: AnyObject, keys: string[], fallback: any = "-") {
  for (const key of keys) {
    if (obj && obj[key] !== undefined && obj[key] !== null && obj[key] !== "") {
      return obj[key];
    }
  }
  return fallback;
}

async function getJson(path: string, fallback: any) {
  try {
    const res = await fetch(`${API_BASE}${path}`, {
      cache: "no-store",
      headers: { Accept: "application/json" },
    });

    if (!res.ok) return fallback;
    return await res.json();
  } catch {
    return fallback;
  }
}

function collectArray(payload: any): any[] {
  if (Array.isArray(payload)) return payload;
  if (Array.isArray(payload?.data)) return payload.data;
  if (Array.isArray(payload?.items)) return payload.items;
  if (Array.isArray(payload?.results)) return payload.results;
  if (Array.isArray(payload?.history)) return payload.history;
  if (Array.isArray(payload?.alerts)) return payload.alerts;
  return [];
}

function statusFromScore(score: number) {
  if (score >= 85) return "EXCELLENT";
  if (score >= 70) return "GOOD";
  if (score >= 55) return "FAIR";
  if (score >= 40) return "POOR";
  return "CRITICAL";
}

function fmt(value: any, digits = 2) {
  const num = Number(value);
  if (!Number.isFinite(num)) return "-";
  return num.toFixed(digits).replace(/\.00$/, "");
}

function deriveQoeScore(metrics: AnyObject) {
  const direct = pick(metrics, ["qoe_score", "qos_score", "score", "quality_score"], null);
  if (direct !== null) return Math.max(0, Math.min(100, Math.round(n(direct, 0))));

  const throughput = n(pick(metrics, ["throughput", "avg_throughput", "download_mbps"], 80), 80);
  const latency = n(pick(metrics, ["latency", "avg_latency"], 30), 30);
  const jitter = n(pick(metrics, ["jitter", "avg_jitter"], 8), 8);
  const packetLoss = n(pick(metrics, ["packet_loss", "loss", "packetLoss"], 0.2), 0.2);

  let score = 100;
  score -= Math.max(0, latency - 20) * 0.8;
  score -= Math.max(0, jitter - 5) * 1.2;
  score -= Math.max(0, packetLoss) * 12;
  score += Math.min(15, throughput / 20);

  return Math.max(0, Math.min(100, Math.round(score)));
}

