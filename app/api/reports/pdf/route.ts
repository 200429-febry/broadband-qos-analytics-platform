function makeQoeTrend(
  history: any[],
  fallbackScore: number,
  throughput: number,
  latency: number,
  jitter: number,
  packetLoss: number
) {
  const trend = history.slice(-12).map((row: AnyObject) => {
    const score = pick(row, ["qoe_score", "qos_score", "score", "quality_score"], null);
    if (score !== null) return n(score, fallbackScore);

    const t = n(pick(row, ["throughput", "avg_throughput", "download_mbps"], throughput), throughput);
    const l = n(pick(row, ["latency", "avg_latency"], latency), latency);
    const j = n(pick(row, ["jitter", "avg_jitter"], jitter), jitter);
    const p = n(pick(row, ["packet_loss", "loss", "packetLoss"], packetLoss), packetLoss);

    let s = 100;
    s -= Math.max(0, l - 20) * 0.8;
    s -= Math.max(0, j - 5) * 1.2;
    s -= Math.max(0, p) * 12;
    s += Math.min(15, t / 20);

    return Math.max(0, Math.min(100, Math.round(s)));
  });

  if (trend.length >= 2) return trend;

  return [
    Math.max(0, fallbackScore - 12),
    Math.max(0, fallbackScore - 8),
    Math.max(0, fallbackScore - 5),
    fallbackScore,
    Math.min(100, fallbackScore + 4),
    Math.max(0, fallbackScore - 3),
    Math.min(100, fallbackScore + 6),
    Math.min(100, fallbackScore + 2),
    Math.min(100, fallbackScore + 8),
    fallbackScore,
    Math.min(100, fallbackScore + 5),
    Math.min(100, fallbackScore + 10),
  ];
}

