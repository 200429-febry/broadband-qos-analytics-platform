          <button
            onClick={refresh}
            className="rounded-xl border border-slate-700 px-5 py-3 text-sm font-bold text-slate-300 hover:bg-slate-800"
          >
            <RefreshCw className="mr-2 inline h-4 w-4" />
            {loading ? "Refreshing..." : "Refresh Data"}
          </button>

          <button
            onClick={() => download("/api/reports/pdf")}
            className="rounded-xl border border-cyan-500/30 bg-cyan-500/10 px-5 py-3 text-sm font-bold text-cyan-300 hover:bg-cyan-500/20"
          >
            <FileText className="mr-2 inline h-4 w-4" />
            Generate Technical PDF
          </button>

          <button
            onClick={() => download("/api/reports/csv")}
            className="rounded-xl border border-emerald-500/30 bg-emerald-500/10 px-5 py-3 text-sm font-bold text-emerald-300 hover:bg-emerald-500/20"
