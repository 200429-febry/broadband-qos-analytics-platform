            : "border-red-500/30 bg-red-500/10"
        }`}
      >
        <div className="flex items-center gap-4">
          {slaPassed ? (
            <CheckCircle2 className="h-8 w-8 text-emerald-300" />
          ) : (
            <AlertTriangle className="h-8 w-8 text-red-300" />
          )}

          <div>
            <h2 className={`text-3xl font-black ${slaPassed ? "text-emerald-300" : "text-red-300"}`}>
              {slaPassed ? "SLA PASSED" : "SLA WATCH / RISK"}
            </h2>
            <p className="mt-1 text-sm text-slate-300">
              Current condition is calculated from real QoE score, active alerts, latency, jitter, and throughput.
            </p>
          </div>
        </div>
      </section>

      <section className="grid gap-4 md:grid-cols-4">
        <Card
          label="Current Throughput"
          value={fmt(metrics.throughput)}
          unit="Mbps"
          icon={Zap}
          accent="text-cyan-300"
          note={metrics.source || "real-qoe-probe"}
        />
        <Card
          label="Current Latency"
          value={fmt(metrics.latency)}
          unit="ms"
          icon={Gauge}
          accent="text-yellow-300"
          note={metrics.timestamp || "-"}
        />
        <Card
          label="Current Jitter"
          value={fmt(metrics.jitter)}
          unit="ms"
          icon={Radio}
          accent="text-purple-300"
          note="Latency variation"
        />
        <Card
          label="QoE Score"
          value={fmt(metrics.qoe_score, 1)}
          unit="/100"
          icon={ShieldCheck}
          accent="text-emerald-300"
          note={metrics.streaming_status || "WAITING"}
        />
      </section>

      <section className="grid gap-4 md:grid-cols-4">
        <Card label="Average Throughput" value={fmt(summary.avgThroughput)} unit="Mbps" icon={Database} />
        <Card label="Min Throughput" value={fmt(summary.minThroughput)} unit="Mbps" icon={Download} />
        <Card label="Average Latency" value={fmt(summary.avgLatency)} unit="ms" icon={Gauge} />
        <Card label="Max Latency" value={fmt(summary.maxLatency)} unit="ms" icon={AlertTriangle} accent="text-yellow-300" />
        <Card label="Average Jitter" value={fmt(summary.avgJitter)} unit="ms" icon={Radio} />
        <Card label="Packet Loss" value={fmt(summary.avgPacketLoss)} unit="%" icon={AlertTriangle} accent="text-red-300" />
        <Card label="Average QoE" value={fmt(summary.avgQoe, 1)} unit="/100" icon={ShieldCheck} accent="text-emerald-300" />
        <Card label="Samples" value={summary.samples} icon={Database} note="real telemetry rows" />
      </section>

      <section className="rounded-3xl border border-slate-800 bg-slate-900/70 p-6">
        <div className="flex items-start justify-between gap-4">
          <div>
            <h2 className="text-xl font-black">Export Integrity</h2>
            <p className="mt-2 text-sm text-slate-400">
              The PDF and CSV buttons above call server-side export endpoints. They do not use screen capture,
              browser print, html2canvas, or DOM screenshot. Therefore floating telemetry widgets and dashboard layout
              will not be embedded into the exported files.
