      <section className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <h1 className="text-3xl font-black">SLA / KPI Technical Report Generator</h1>
          <p className="mt-2 max-w-4xl text-slate-400">
            Structured server-side PDF and CSV export generated from real browser-to-Cloud Run QoE telemetry.
            This export does not capture the dashboard screen, so floating widgets will not appear in the report.
