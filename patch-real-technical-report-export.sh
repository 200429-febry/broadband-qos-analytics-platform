                  <td className="p-3">{item.source || "-"}</td>
                </tr>
              ))}

              {history.length === 0 ? (
                <tr>
                  <td colSpan={7} className="p-6 text-center text-slate-500">
                    No telemetry samples available yet. Open Streaming QoE or keep the dashboard active to feed the real probe.
                  </td>
                </tr>
              ) : null}
            </tbody>
          </table>
        </div>
      </section>
    </main>
  );
